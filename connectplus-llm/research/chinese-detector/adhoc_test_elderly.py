def main() -> None:
    n = len(STATEMENTS)
    print(f"(sanity check: {n} statements loaded)\n")
    correct = 0
    failures: list[tuple[str, float]] = []
    for text in STATEMENTS:
        result = classify(text)
        ok = result.lang == "zh"
        correct += ok
        if not ok:
            failures.append((text, result.confidence))

    print(f"{correct}/{n} = {correct / n:.1%} correctly identified as Chinese\n")
    if failures:
        print("MISCLASSIFIED:")
        for text, conf in failures:
            print(f"  ({conf:.1%} confidence, wrong) {text}")
    else:
        print("No misclassifications.")


if __name__ == "__main__":
    main()
